// 4. Hex Decode 32B -> 16B (écriture directe, 0-fill sur erreur pour éviter la double copie inutile)
uint32_t c2archsimd_hex_decode32(const uint8_t in[32], uint8_t out[16]) {
    for (int i = 0; i < 16; i++) {
        uint8_t hi = c2archsimd_hex_lut256[in[i * 2]];
        uint8_t lo = c2archsimd_hex_lut256[in[i * 2 + 1]];
        if (hi == 0xFF || lo == 0xFF) {
            for (int k = 0; k < 16; k++) {
                out[k] = 0;
            }
            return C2ARCHSIMD_INVALID_HEX;
        }
        out[i] = (uint8_t)((hi << 4) | lo);
    }
    return C2ARCHSIMD_OK;
}

static const uint8_t c2archsimd_vint_lens[4] = {1, 2, 4, 8};

// 5. VarInt Batch Lengths Scalaire
void c2archsimd_vint_lens32(const uint8_t in[32], uint8_t out[32]) {
    for (int i = 0; i < 32; i++) {
        out[i] = c2archsimd_vint_lens[in[i] >> 6];
    }
}

// 6. Photometric Solid Blend Scalaire (8 pixels = 32 octets)
void c2archsimd_blend_solid_photometric8(const uint32_t in[8], const c2archsimd_solid_blend_ctx_t *ctx, uint32_t out[8]) {
    uint32_t sa = ctx->sa;
    uint32_t inv_a = ctx->inv_a;
    uint32_t sr_scaled = ctx->sr_scaled;
    uint32_t sg_scaled = ctx->sg_scaled;
    uint32_t sb_scaled = ctx->sb_scaled;
    const uint16_t *lut_lin = ctx->lut_srgb_to_lin;
    const uint8_t *lut_srgb = ctx->lut_lin_to_srgb;

    for (int k = 0; k < 8; k++) {
        uint32_t d = in[k];
        uint32_t dr = d & 0xFF;
        uint32_t dg = (d >> 8) & 0xFF;
        uint32_t db = (d >> 16) & 0xFF;
        uint32_t da = (d >> 24) & 0xFF;

        uint32_t dr_lin = (uint32_t)lut_lin[dr];
        uint32_t dg_lin = (uint32_t)lut_lin[dg];
        uint32_t db_lin = (uint32_t)lut_lin[db];

        uint32_t out_r_lin = (sr_scaled + dr_lin * inv_a + 127) / 255;
        uint32_t out_g_lin = (sg_scaled + dg_lin * inv_a + 127) / 255;
        uint32_t out_b_lin = (sb_scaled + db_lin * inv_a + 127) / 255;
        uint32_t out_a = sa + (da * inv_a + 127) / 255;

        if (out_r_lin > 65535) out_r_lin = 65535;
        if (out_g_lin > 65535) out_g_lin = 65535;
        if (out_b_lin > 65535) out_b_lin = 65535;
        if (out_a > 255) out_a = 255;

        uint32_t out_r = (uint32_t)lut_srgb[out_r_lin >> 4];
        uint32_t out_g = (uint32_t)lut_srgb[out_g_lin >> 4];
        uint32_t out_b = (uint32_t)lut_srgb[out_b_lin >> 4];

        out[k] = out_r | (out_g << 8) | (out_b << 16) | (out_a << 24);
    }
}

